export interface VoiceProfile {
  experience: string;
  style: string;
  topics: string;
  avoid: string;
  additional: string;
}
const marker = '[AutoPost: perfil de voz v1]';
const headings = [
  'Experiencia',
  'Estilo',
  'Temas',
  'Expresiones a evitar',
  'Instrucciones adicionales',
];
const keys: (keyof VoiceProfile)[] = ['experience', 'style', 'topics', 'avoid', 'additional'];
export function serializeVoice(value: VoiceProfile): string {
  return (
    marker + '\n\n' + keys.map((key, i) => '## ' + headings[i] + '\n' + value[key]).join('\n\n')
  );
}
export function parseVoice(prompt: string): VoiceProfile {
  const empty: VoiceProfile = {
    experience: '',
    style: '',
    topics: '',
    avoid: '',
    additional: prompt,
  };
  if (!prompt.startsWith(marker + '\n\n')) return empty;
  const result = { ...empty, additional: '' };
  let rest = prompt.slice(marker.length + 2);
  for (let i = 0; i < keys.length; i++) {
    const heading = '## ' + headings[i] + '\n';
    if (!rest.startsWith(heading)) return empty;
    rest = rest.slice(heading.length);
    const next = i === keys.length - 1 ? -1 : rest.indexOf('\n\n## ' + headings[i + 1] + '\n');
    if (i < keys.length - 1 && next < 0) return empty;
    result[keys[i]] = next < 0 ? rest : rest.slice(0, next);
    if (next >= 0) rest = rest.slice(next + 2);
  }
  // Only consume the exact format generated by this application.
  return serializeVoice(result) === prompt ? result : empty;
}
